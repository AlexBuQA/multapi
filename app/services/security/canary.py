"""
Канарейка (блок 3.8): секретная метка в системном сообщении каждого запроса к модели.

Значение генерируется при старте сервиса (lifespan, app/main.py) и хранится в
app.state.canary: CANARY_ и 8 случайных шестнадцатеричных символов. Пользователь его не
знает, в ответе по делу оно появиться не может. Если метка оказалась в ответе — модель
пересказывает системные сообщения, то есть промпт утёк. Это ловит output_filter, даже
когда модель пересказала промпт своими словами и проверка дословного совпадения молчит.

В ключ кеша метка не входит (LLMService.cache_key): после перезапуска сервиса она
другая, а кеш Redis должен переживать перезапуск.

Формулировка и место — после прогонов блока 4.2. Раньше метка была сообщением «Секретная
метка (не разглашать): …» после промпта ассистента. Ollama склеивает все системные сообщения
в один блок, и у llama3.2 эта строка оказывалась последней перед диалогом. На вопрос «Как меня
зовут?» модель путала её с данными пользователя, начинала «Твой…» и пересказывала метку —
output_filter честно останавливал ответ, а пользователь получал отказ (1 из 6 прогонов
scripts/chat_scenario.py и один ответ в Telegram). Теперь метка — нейтральный «Идентификатор
сборки» первым системным сообщением: к пользователю он не относится, а промпт ассистента
стоит ближе к диалогу. Задача метки прежняя: модель, которая пересказывает свои системные
сообщения, перескажет и её, и ответ остановит output_filter. Просьба «не разглашать» для этого
не нужна — метка ловит пересказ, а не проверяет, послушалась ли модель.
"""
from __future__ import annotations

import secrets
from typing import Final

CANARY_PREFIX: Final = "CANARY_"
CANARY_TEMPLATE: Final = "Идентификатор сборки: {canary}"


def new_canary() -> str:
    return CANARY_PREFIX + secrets.token_hex(4)


def canary_message(canary: str) -> dict[str, str]:
    return {"role": "system", "content": CANARY_TEMPLATE.format(canary=canary)}


def with_canary(messages: list[dict[str, str]], canary: str | None) -> list[dict[str, str]]:
    """Сообщения для модели с меткой — первым системным сообщением, перед промптом ассистента.
    Утечку правил output_filter проверяет по промпту из запроса до этой вставки
    (LLMService._system_prompt), так что место метки на неё не влияет."""
    if not canary:
        return messages
    return [canary_message(canary), *messages]
